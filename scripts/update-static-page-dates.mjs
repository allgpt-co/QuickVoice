#!/usr/bin/env node
/**
 * Regenerate apps/web/data/static-page-dates.mjs from git history.
 *
 * For every static sitemap route listed in apps/web/data/static-page-sources.mjs,
 * record the committer date (YYYY-MM-DD) of the last commit that touched any of
 * the route's source paths. The sitemap emits these as <lastmod>, which is the
 * strongest recrawl signal Search Console accepts for pages whose content changed.
 *
 * Usage:
 *   node scripts/update-static-page-dates.mjs          # rewrite the dates file
 *   node scripts/update-static-page-dates.mjs --check  # exit 1 if the file is stale
 *
 * Run it AFTER committing a change that touches static pages or their data
 * (the dates come from commit history, so a pre-commit run is already stale),
 * then commit the regenerated file. `--check` needs full history; CI shallow
 * clones must fetch with depth 0 before using it.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { STATIC_PAGE_SOURCES } from "../apps/web/data/static-page-sources.mjs";

const root = resolve(fileURLToPath(new URL("../", import.meta.url)));
const target = resolve(root, "apps/web/data/static-page-dates.mjs");
const check = process.argv.includes("--check");

function lastCommitDate(paths) {
  const existing = paths.filter((path) => existsSync(resolve(root, path)));
  if (existing.length === 0) throw new Error(`No existing source paths among: ${paths.join(", ")}`);
  const result = spawnSync("git", ["log", "-1", "--format=%cs", "--", ...existing], { cwd: root, encoding: "utf8" });
  if (result.status !== 0) throw new Error(result.stderr || "git log failed");
  const date = result.stdout.trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error(`Unexpected git date "${date}" for ${existing[0]}`);
  return date;
}

export function renderDatesModule(dates) {
  const lines = Object.keys(dates)
    .sort()
    .map((route) => `  ${JSON.stringify(route)}: ${JSON.stringify(dates[route])},`);
  return [
    "/**",
    " * GENERATED by scripts/update-static-page-dates.mjs — do not edit by hand.",
    " * Last commit date (UTC calendar day) for each static sitemap route's sources.",
    " */",
    "export const STATIC_PAGE_LAST_MODIFIED = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

try {
  const dates = Object.fromEntries(
    Object.entries(STATIC_PAGE_SOURCES).map(([route, paths]) => [route, lastCommitDate(paths)]),
  );
  const output = renderDatesModule(dates);
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (check) {
    if (current !== output) {
      process.stderr.write("static-page-dates.mjs is stale; run node scripts/update-static-page-dates.mjs\n");
      process.exitCode = 1;
    } else {
      process.stdout.write("static-page-dates.mjs is current.\n");
    }
  } else {
    writeFileSync(target, output);
    process.stdout.write(`Wrote ${Object.keys(dates).length} route dates to apps/web/data/static-page-dates.mjs\n`);
  }
} catch (error) {
  process.stderr.write(`[static-page-dates] ${error.message}\n`);
  process.exitCode = 1;
}
